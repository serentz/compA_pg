-- Base de test du cluster 2 (comparee) : poc_pg, avec des ecarts volontaires par rapport au cluster 1.
-- A executer en superutilisateur :
--     psql -h pg01 -p 5434 -U postgres -d postgres -f 02_create_poc_db_cluster2.sql
\set ON_ERROR_STOP on

-- Roles : app_ro sans login, batch_user absent, reporting_user en plus, app_rw sans limite de connexions
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_owner')      THEN CREATE ROLE app_owner  NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_rw')         THEN CREATE ROLE app_rw     LOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ro')         THEN CREATE ROLE app_ro     NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'reporting_user') THEN CREATE ROLE reporting_user LOGIN; END IF;
END $$;
GRANT app_ro TO app_rw;

DROP DATABASE IF EXISTS poc_pg;
CREATE DATABASE poc_pg OWNER app_owner ENCODING 'UTF8' TEMPLATE template0;
-- ecart : pas de search_path propre a la base

\c poc_pg
CREATE EXTENSION pg_trgm;
CREATE EXTENSION hstore;          -- ecart : hstore au lieu de citext

CREATE SCHEMA app AUTHORIZATION app_owner;
SET ROLE app_owner;
SET search_path = app, public;

CREATE SEQUENCE seq_invoice START 1000 INCREMENT 1 CACHE 1;
CREATE SEQUENCE seq_batch   START 1    INCREMENT 10 CACHE 10;    -- ecart : increment

CREATE TABLE customers (
    id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        varchar(150) NOT NULL,                           -- ecart : longueur
    email       text,                                            -- ecart : type
    country     char(2) NOT NULL DEFAULT 'FR',
    created_at  timestamptz NOT NULL DEFAULT now(),
    phone       varchar(20)                                      -- ecart : colonne en plus
);
CREATE TABLE orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer NOT NULL REFERENCES customers (id) ON DELETE CASCADE,   -- ecart : action FK
    invoice_no   bigint DEFAULT nextval('app.seq_invoice'),
    status       varchar(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'PAID', 'SHIPPED')),  -- ecart : CHECK
    total        numeric(12,2) NOT NULL DEFAULT 0,
    comment      text NOT NULL DEFAULT '',                       -- ecart : NOT NULL + defaut
    ordered_at   timestamp NOT NULL DEFAULT now()
);
CREATE TABLE order_items (
    order_id    integer NOT NULL,                                -- ecart : pas de cle etrangere
    line_no     smallint NOT NULL,
    sku         varchar(30) NOT NULL,
    qty         integer NOT NULL CHECK (qty > 0),
    price       numeric(10,2) NOT NULL,
    PRIMARY KEY (order_id, line_no)
);
CREATE TABLE audit_log (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tbl       text NOT NULL,
    action    char(1) NOT NULL,
    at        timestamptz NOT NULL DEFAULT now()
);
-- ecart : legacy_codes absente ; table en plus
CREATE TABLE tmp_import (id integer PRIMARY KEY, payload text);

CREATE INDEX ux_customers_email ON customers (email);            -- ecart : non unique
CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_status ON orders (status) WHERE status <> 'CANCELLED';
-- ecart : ix_items_sku absent
CREATE INDEX ix_customers_name_trgm ON customers USING gin (name gin_trgm_ops);
CREATE INDEX ix_orders_ordered_at ON orders (ordered_at);         -- ecart : index en plus

CREATE VIEW v_open_orders AS
    SELECT o.id, c.name, o.total FROM orders o JOIN customers c ON c.id = o.customer_id WHERE o.status IN ('NEW', 'PAID', 'SHIPPED');  -- ecart : code
CREATE VIEW v_customer_totals AS
    SELECT c.id, c.name, coalesce(sum(o.total), 0) AS total FROM customers c LEFT JOIN orders o ON o.customer_id = c.id GROUP BY c.id, c.name;
-- ecart : vue materialisee absente ; vue en plus
CREATE VIEW v_tmp_import AS SELECT id FROM tmp_import;

CREATE FUNCTION order_total(p_order integer) RETURNS numeric LANGUAGE sql STABLE AS
$$ SELECT coalesce(sum(qty * price), 0) FROM app.order_items WHERE order_id = p_order $$;
CREATE FUNCTION audit_trg() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN INSERT INTO app.audit_log (tbl, action) VALUES (TG_TABLE_NAME, TG_OP); RETURN NEW; END $$;   -- ecart : code
CREATE PROCEDURE purge_audit(p_days integer) LANGUAGE sql AS
$$ DELETE FROM app.audit_log WHERE at < now() - make_interval(days => p_days) $$;

CREATE TRIGGER trg_orders_audit AFTER INSERT OR UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION audit_trg();
-- ecart : trg_customers_audit absent

RESET ROLE;
GRANT USAGE ON SCHEMA app TO app_rw, app_ro;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO app_rw;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA app TO app_ro;       -- ecart : INSERT en plus
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO app_rw;
GRANT EXECUTE ON FUNCTION app.order_total(integer) TO app_rw, app_ro;
-- ecart : EXECUTE non retire de PUBLIC

