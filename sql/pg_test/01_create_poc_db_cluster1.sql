--     psql -h pgdb01 -p 5433 -U postgres -d postgres -f 01_create_poc_db_cluster1.sql
\set ON_ERROR_STOP on

-- Roles (niveau cluster)
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_owner')  THEN CREATE ROLE app_owner  NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_rw')     THEN CREATE ROLE app_rw     LOGIN CONNECTION LIMIT 20; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ro')     THEN CREATE ROLE app_ro     LOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'batch_user') THEN CREATE ROLE batch_user LOGIN CREATEDB; END IF;
END $$;
GRANT app_ro TO app_rw;

DROP DATABASE IF EXISTS poc_pg;
CREATE DATABASE poc_pg OWNER app_owner ENCODING 'UTF8' TEMPLATE template0;
ALTER DATABASE poc_pg SET search_path = app, public;

\c poc_pg
CREATE EXTENSION pg_trgm;
CREATE EXTENSION citext;

CREATE SCHEMA app AUTHORIZATION app_owner;
SET ROLE app_owner;
SET search_path = app, public;

CREATE SEQUENCE seq_invoice START 1000 INCREMENT 1 CACHE 1;
CREATE SEQUENCE seq_batch   START 1    INCREMENT 5 CACHE 10;

CREATE TABLE customers (
    id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    email       citext,
    country     char(2) NOT NULL DEFAULT 'FR',
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
    invoice_no   bigint DEFAULT nextval('app.seq_invoice'),
    status       varchar(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED')),
    total        numeric(12,2) NOT NULL DEFAULT 0,
    comment      text,
    ordered_at   timestamp NOT NULL DEFAULT now()
);
CREATE TABLE order_items (
    order_id    integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no     smallint NOT NULL,
    sku         varchar(30) NOT NULL,
    qty         integer NOT NULL CHECK (qty > 0),
    price       numeric(10,2) NOT NULL,
    PRIMARY KEY (order_id, line_no)
);
CREATE TABLE audit_log (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tbl       text NOT NULL,
    action    char(1) NOT NULL,
    at        timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE legacy_codes (code varchar(10) PRIMARY KEY, label varchar(50));

CREATE UNIQUE INDEX ux_customers_email ON customers (email);
CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_status ON orders (status) WHERE status <> 'CANCELLED';
CREATE INDEX ix_items_sku ON order_items (sku);
CREATE INDEX ix_customers_name_trgm ON customers USING gin (name gin_trgm_ops);

CREATE VIEW v_open_orders AS
    SELECT o.id, c.name, o.total FROM orders o JOIN customers c ON c.id = o.customer_id WHERE o.status IN ('NEW', 'PAID');
CREATE VIEW v_customer_totals AS
    SELECT c.id, c.name, coalesce(sum(o.total), 0) AS total FROM customers c LEFT JOIN orders o ON o.customer_id = c.id GROUP BY c.id, c.name;
CREATE MATERIALIZED VIEW mv_sales_by_country AS
    SELECT c.country, sum(o.total) AS total FROM customers c JOIN orders o ON o.customer_id = c.id GROUP BY c.country;

CREATE FUNCTION order_total(p_order integer) RETURNS numeric LANGUAGE sql STABLE AS
$$ SELECT coalesce(sum(qty * price), 0) FROM app.order_items WHERE order_id = p_order $$;
CREATE FUNCTION audit_trg() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN INSERT INTO app.audit_log (tbl, action) VALUES (TG_TABLE_NAME, left(TG_OP, 1)); RETURN NEW; END $$;
CREATE PROCEDURE purge_audit(p_days integer) LANGUAGE sql AS
$$ DELETE FROM app.audit_log WHERE at < now() - make_interval(days => p_days) $$;

CREATE TRIGGER trg_orders_audit AFTER INSERT OR UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION audit_trg();
CREATE TRIGGER trg_customers_audit AFTER INSERT ON customers FOR EACH ROW EXECUTE FUNCTION audit_trg();

RESET ROLE;
GRANT USAGE ON SCHEMA app TO app_rw, app_ro;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO app_rw;
GRANT SELECT ON ALL TABLES IN SCHEMA app TO app_ro;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO app_rw;
GRANT EXECUTE ON FUNCTION app.order_total(integer) TO app_rw, app_ro;
REVOKE EXECUTE ON FUNCTION app.order_total(integer) FROM PUBLIC;

